
describe('cypress commands test (positive)', () => { 
  beforeEach(() => {
    cy.login()
cy.visit("./src/index.html?skipCaptcha=true", {
  onBeforeLoad(win) {
    win.localStorage.setItem("cookieConsent", "accepted")
     }
    })

  })
it('tests .visit', () => {
cy.get('#codeInput').type("cy.visit()")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.visit() // Visited URL ") 
  .and('be.visible')
})
it('tests .get', () => {
cy.get('#codeInput').type("cy.get()")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.get() // Got element by selector") 
  .and('be.visible')
})
it('it shows a warning when entering and running a not-implemented Cypress command', () => {
cy.get('#codeInput').type("cy.contains()")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Warning:")
  .and ('contain', "The `cy.contains` command has not been implemented yet.") 
  .and('be.visible')
})
it("it successfully simulates a Cypress command (e.g., cy.log('Yay!'))", () => {
cy.get('#codeInput').type("cy.log(Yay!)")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.log(Yay!) // Logged message Yay!") 
  .and('be.visible')

})


it('it shows an error when entering and running an invalid Cypress command .', () => {
cy.get('#codeInput').type("cy.coantains()")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Error:")
  .and ('contain', "Invalid Cypress command: cy.coantains()") 
  .and('be.visible')
})
it('it shows an error when entering and running a valid Cypress command without parentheses', () => {
cy.get('#codeInput').type("cy.visit")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Error:")
  .and ('contain', "Missing parentheses on `cy.visit` command") 
  .and('be.visible')
})
it('it asks for help and gets common Cypress commands and examples with a link to the docs', () => {
cy.get('#codeInput').type("help")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
.should('contain', "Common Cypress commands and examples:")
.and('contain',"For more commands and details, visit the official Cypress API documentation.")
.and('be.visible')
cy.get('a[href="https://docs.cypress.io/api/table-of-contents"]')
.should('have.attr', "target", "_blank" )
.and('be.visible')
})
it('it maximizes and minimizes a simulation result', () => {
cy.get('#expandIcon')
.should('be.visible')
.click()
cy.get('#collapseIcon')
.should('be.visible')
.click()
})
it('it logs out successfully', () => {
cy.get('#sandwich-menu').click()
cy.get('#logoutButton').click()
cy.contains("button", "Login")
.should('be.visible')
cy.get('#codeInput')
.should('not.be.visible')
})
it('it shows and hides the logout button' , () => {
cy.get('#sandwich-menu').click()
cy.get('#logoutButton')
.should('be.visible')
cy.get('#sandwich-menu').click()
cy.get('#logoutButton')
.should('not.be.visible')
})
it('it shows the running state before showing the final result' , () => {
cy.get('#codeInput').type("cy.log()")
cy.get('#runButton')
.should('be.enabled')
cy.get('#runButton').click()
cy.contains('button', "Running...")
.should('be.visible')
.and('be.disabled')
cy.get("#outputArea", { timeout: 6000 })
.should('contain', "Running... Please wait.")
.and('be.visible')
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.log() // Logged message") 
  .and('be.visible')
cy.get('#runButton', { timeout: 6000 })
.should('be.enabled')
})
it('it checks the run button disabled and enabled states' , () => {
cy.get('#runButton')
.as('runbtn')
.should('be.disabled')
cy.get('#codeInput')
.type("asdwdasdw")
cy.get('@runbtn')
.should('be.enabled')
cy.get('#codeInput')
.clear()
cy.get('#codeInput')
.should('have.value', "")
cy.get('@runbtn')
.should('be.disabled')

})
it('it clears the code input when logging off then logging in again' , () => {
cy.get('#codeInput')
.type("cy.log('yay')")
cy.get('#sandwich-menu').click()
cy.get('#logoutButton').click()
cy.contains('button', "Login").click()
cy.get('#codeInput')
.should('have.value', "")
})
it('it disables the run button when logging off then logging in again' , () => {
cy.get('#codeInput')
.type("cy.log('yay')")
cy.get('#sandwich-menu').click()
cy.get('#logoutButton').click()
cy.contains('button', "Login").click()
cy.get('#runButton')
.should('be.disabled')
})
it('it clears the code output when logging off then logging in again' , () => {
cy.get('#codeInput')
.type("cy.log('yay')")
cy.get('#runButton').click()
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.log('yay') // Logged message 'yay'")
  cy.get('#sandwich-menu').click()
cy.get('#logoutButton').click()
cy.contains('button', "Login").click()
cy.get('#outputArea')
.should('not.contain', "cy.log('yay')")
})
it.only('' , () => {
cy.run("cy.log('Yo!')")
cy.get("#outputArea", { timeout: 6000 })
  .should('contain', "Success:")
  .and ('contain', "cy.log('Yo!') // Logged message 'Yo!'") 
  .and('be.visible')
})
})
describe.only('not consenting automatcally to cookies', () => {
  beforeEach(() => {
    cy.login()
    cy.visit("./src/index.html?skipCaptcha=true")
  })
it('it consents to the cookies usage' , () => {
cy.get('#cookieConsent')
.as('cookieConsentBanner')
.find('button:contains(Accept)')
.click()
cy.get('@cookieConsentBanner')
.should('not.be.visible')
cy.window()
.its('localStorage')
.invoke('getItem', 'cookieConsent')
.should('equal', 'accepted')
})
it('it declines the cookies usage', () => {
cy.get('#cookieConsent')
.as("cookieConsentBanner")
.find('button:contains(Decline)')
.click()
cy.get('@cookieConsentBanner')
.should('not.be.visible')
cy.window()
.its('localStorage')
.invoke('getItem', 'cookieConsent')
.should('equal', 'declined')
})
})
describe('Captcha',() => {
beforeEach(() => {
    cy.visit("./src/index.html")
        cy.contains("button", "Login").click()
})

it("it disables the captcha verify button when no answer is provided or it's cleared" , () => {
cy.get('#verifyCaptcha')
.as('captchabtn')
.should('be.disabled')
cy.get('#captchaInput')
.type("3")
cy.get('@captchabtn')
.should('be.enabled')
cy.get('#captchaInput')
.clear()
cy.get('@captchabtn')
.should('be.disabled')
})
it('it shows an error on a wrong captcha answer and goes back to its initial state', () => {
cy.get('#captchaInput')
.type("32223")
cy.get('#verifyCaptcha')
.click()
cy.get('#captchaError')
.should('be.visible')
.and('contain', 'Incorrect answer, please try again.')
cy.get('#captchaInput')
.should('have.value', "")
cy.get('#verifyCaptcha')
.should('be.disabled')
})
it("it doesn't show the cookie consent banner on the login page" , () => {
cy.clearAllLocalStorage()
cy.reload()
cy.get('#cookieConsent').should('not.be.visible')
})
})

